// Refreshes contributions.js from your public GitHub contribution calendar.
//
//   node scripts/update-contributions.mjs            (defaults to ronit567)
//   node scripts/update-contributions.mjs <username>
//
// GitHub's page isn't an API, so everything parsed from it is checked before
// anything is written: if the markup changes, this fails loudly and leaves the
// existing file alone.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const user = process.argv[2] || 'ronit567';
if (!/^[a-z\d](?:[a-z\d]|-(?=[a-z\d])){0,38}$/i.test(user)) throw new Error(`Not a GitHub username: ${user}`);

const res = await fetch(`https://github.com/users/${user}/contributions`);
if (!res.ok) throw new Error(`GitHub answered ${res.status} for ${user}`);
const html = await res.text();

// Each day is a <td data-date=... id=... data-level=...>; its count lives in a
// <tool-tip for=that-id> like "3 contributions on May 2nd." or "No contributions on ...".
const attr = (tag, name) => (tag.match(new RegExp(`\\s${name}="([^"]*)"`)) || [])[1];
const counts = new Map();
for (const [, id, text] of html.matchAll(/<tool-tip\b[^>]*\bfor="([^"]+)"[^>]*>([^<]*)<\/tool-tip>/g)) {
  const m = text.trim().match(/^(No|[\d,]+) contributions? on /);
  if (m) counts.set(id, m[1] === 'No' ? 0 : Number(m[1].replace(/,/g, '')));
}
const days = [];
for (const [tag] of html.matchAll(/<td\b[^>]*\bContributionCalendar-day\b[^>]*>/g)) {
  const date = attr(tag, 'data-date');
  const level = Number(attr(tag, 'data-level'));
  const count = counts.get(attr(tag, 'id'));
  if (!date) continue; // padding cells have no date
  days.push([date, count, level]);
}
days.sort((a, b) => (a[0] < b[0] ? -1 : 1));

// Sanity checks: about a year of consecutive days, every one with a count and a level
const problems = [];
if (days.length < 350 || days.length > 380) problems.push(`expected about a year of days, got ${days.length}`);
days.forEach(([date, count, level], i) => {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) problems.push(`bad date ${date}`);
  if (!Number.isInteger(count) || count < 0) problems.push(`no count for ${date}`);
  if (!(level >= 0 && level <= 4)) problems.push(`bad level ${level} on ${date}`);
  if (i > 0 && Date.parse(date) - Date.parse(days[i - 1][0]) !== 86400000) problems.push(`gap before ${date}`);
});
if (problems.length) throw new Error(`GitHub's page didn't parse cleanly:\n  ${problems.slice(0, 5).join('\n  ')}`);

const total = days.reduce((sum, d) => sum + d[1], 0);
const data = { user, updated: new Date().toISOString().slice(0, 10), total, days };
const out = fileURLToPath(new URL('../contributions.js', import.meta.url));
await writeFile(
  out,
  `// Generated by scripts/update-contributions.mjs. Re-run it to refresh.\nwindow.CONTRIBUTIONS = ${JSON.stringify(data)};\n`
);
console.log(`Wrote ${days.length} days, ${total} contributions, for ${user}.`);
